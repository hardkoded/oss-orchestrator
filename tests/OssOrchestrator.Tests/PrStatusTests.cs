using System.Text.Json;
using OssOrchestrator.Agent;
using Xunit;

namespace OssOrchestrator.Tests;

public class PrStatusTests
{
    private static JsonElement Checks(string json) => JsonDocument.Parse(json).RootElement.Clone();

    [Fact]
    public void Conflicting_PR_is_conflicted_even_when_checks_pass()
    {
        var rollup = Checks("""[{"status":"COMPLETED","conclusion":"SUCCESS"}]""");
        Assert.Equal("conflicted", PrStatus.From("CONFLICTING", rollup));
    }

    [Fact]
    public void No_checks_yet_is_pending()
    {
        Assert.Equal("pending", PrStatus.From("MERGEABLE", Checks("[]")));
    }

    [Fact]
    public void All_checks_passing_is_ready()
    {
        var rollup = Checks("""[{"status":"COMPLETED","conclusion":"SUCCESS"},{"status":"COMPLETED","conclusion":"SKIPPED"}]""");
        Assert.Equal("ready", PrStatus.From("MERGEABLE", rollup));
    }

    [Fact]
    public void A_check_still_running_is_building()
    {
        var rollup = Checks("""[{"status":"COMPLETED","conclusion":"SUCCESS"},{"status":"IN_PROGRESS","conclusion":""}]""");
        Assert.Equal("building", PrStatus.From("MERGEABLE", rollup));
    }

    [Fact]
    public void A_failed_check_is_failed_even_while_others_run()
    {
        var rollup = Checks("""[{"status":"COMPLETED","conclusion":"FAILURE"},{"status":"IN_PROGRESS","conclusion":""}]""");
        Assert.Equal("failed", PrStatus.From("MERGEABLE", rollup));
        Assert.True(PrStatus.AnyRunning(rollup));
    }

    [Theory]
    [InlineData("""[{"status":"COMPLETED","conclusion":"FAILURE"},{"status":"COMPLETED","conclusion":"SUCCESS"}]""", false)]
    [InlineData("""[{"status":"COMPLETED","conclusion":"FAILURE"},{"state":"PENDING"}]""", true)]
    [InlineData("""[{"state":"ERROR"},{"state":"EXPECTED"}]""", true)]
    public void Checks_are_running_until_every_check_has_finished(string json, bool expected)
    {
        Assert.Equal(expected, PrStatus.AnyRunning(Checks(json)));
    }

    [Theory]
    [InlineData("""{"headRefName":"claude/clever-curie-2z9y6j","closingIssuesReferences":[{"number":3826}]}""", 3826)]
    [InlineData("""{"headRefName":"fix/1531-short-name","closingIssuesReferences":[{"number":1600},{"number":1531}]}""", 1531)]
    [InlineData("""{"headRefName":"fix/1531-short-name","closingIssuesReferences":[]}""", 1531)]
    [InlineData("""{"headRefName":"fix/1531-short-name"}""", 1531)]
    public void The_issue_comes_from_the_closing_reference_unless_the_branch_number_is_one_of_them(string pr, int expected)
    {
        Assert.Equal(expected, GitHub.IssueOf(Checks(pr)));
    }

    [Theory]
    [InlineData("fix/1531-short-name", 1531)]
    [InlineData("feature/2-x", 2)]
    [InlineData("main", null)]
    public void Issue_number_comes_from_the_branch_name(string branch, int? expected)
    {
        Assert.Equal(expected, GitHub.IssueFromBranch(branch));
    }

    [Fact]
    public void Legacy_status_contexts_are_read_by_state()
    {
        Assert.Equal("failed", PrStatus.From("MERGEABLE", Checks("""[{"state":"ERROR"}]""")));
        Assert.Equal("building", PrStatus.From("MERGEABLE", Checks("""[{"state":"PENDING"}]""")));
        Assert.Equal("ready", PrStatus.From("MERGEABLE", Checks("""[{"state":"SUCCESS"}]""")));
    }
}

public class SessionFromPrBodyTests
{
    [Fact]
    public void Reads_the_session_link_as_a_cse_id() =>
        Assert.Equal("cse_01Ls2e21syom6xzqKJ6pFBrs",
            OssOrchestrator.Agent.GitHub.SessionFromPrBody("Closes #1\n_Generated by [Claude Code](https://claude.ai/code/session_01Ls2e21syom6xzqKJ6pFBrs)_"));

    [Fact]
    public void Is_null_without_a_link() => Assert.Null(OssOrchestrator.Agent.GitHub.SessionFromPrBody("Closes #1"));
}

public class PrCommentTests
{
    private static JsonElement Pr(string json) => JsonDocument.Parse(json).RootElement.Clone();
    private static readonly HashSet<string> Own = new(StringComparer.OrdinalIgnoreCase) { "kblok" };

    [Fact]
    public void The_workers_own_comments_and_reviews_are_ignored()
    {
        var pr = Pr("""{"comments":[{"author":{"login":"kblok"},"createdAt":"2026-11-17T10:00:00Z"}],"reviews":[{"author":{"login":"KBlok"},"submittedAt":"2026-11-17T11:00:00Z"}]}""");
        Assert.Null(GitHub.LatestOutsideComment(pr, Own));
    }

    [Fact]
    public void The_newest_comment_or_review_by_someone_else_wins()
    {
        var pr = Pr("""{"comments":[{"author":{"login":"alice"},"createdAt":"2026-11-17T10:00:00Z"}],"reviews":[{"author":{"login":"coderabbitai"},"submittedAt":"2026-11-17T12:00:00Z"},{"author":{"login":"kblok"},"submittedAt":"2026-11-17T13:00:00Z"}]}""");
        Assert.Equal(DateTimeOffset.Parse("2026-11-17T12:00:00Z"), GitHub.LatestOutsideComment(pr, Own));
    }

    [Fact]
    public void A_PR_without_comments_has_none() =>
        Assert.Null(GitHub.LatestOutsideComment(Pr("""{"comments":[],"reviews":[]}"""), Own));
}
